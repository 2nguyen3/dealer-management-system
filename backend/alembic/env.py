from alembic import context
from sqlalchemy import create_engine
from sqlalchemy.pool import NullPool

from app.common import commands  # noqa: F401
from app.core.config import get_settings
from app.db.base import Base, include_name
from app.modules.agency_types import models as agency_type_models  # noqa: F401
from app.modules.auth import models  # noqa: F401
from app.modules.districts import models as district_models  # noqa: F401
from app.modules.document_core import models as document_models  # noqa: F401
from app.modules.units import models as unit_models  # noqa: F401
from app.modules.user_groups import models as group_models  # noqa: F401
from app.modules.users import models as user_models  # noqa: F401

# The initial schema uses reviewed SQL (domains/routines are not autogenerated).
# Import future Base models here before autogenerating their migrations.
target_metadata = Base.metadata
url = context.config.attributes.get("url")
if url is None:
    url = get_settings().database_url()


if context.is_offline_mode():
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        compare_type=True,
        include_schemas=True,
        include_name=include_name,
        version_table_schema="public",
    )
    with context.begin_transaction():
        context.run_migrations()
else:
    engine = create_engine(url, poolclass=NullPool, connect_args={"prepare_threshold": None})
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            include_schemas=True,
            include_name=include_name,
            version_table_schema="public",
        )
        with context.begin_transaction():
            context.run_migrations()
    engine.dispose()
